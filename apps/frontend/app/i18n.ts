export type Lang = "en" | "ru" | "de";
export type ThemeMode = "light" | "dark";

export const LANG_KEY = "sofortbot_lang";
export const LANG_CHANGE_EVENT = "sofortbot:lang-change";
export const THEME_KEY = "sofortbot_theme";

export function isLang(value: string | null): value is Lang {
  return value === "en" || value === "ru" || value === "de";
}

export function readStoredLang(): Lang {
  if (typeof window === "undefined") return "en";
  const saved = window.localStorage.getItem(LANG_KEY);
  return isLang(saved) ? saved : "en";
}

export function writeStoredLang(lang: Lang) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(LANG_KEY, lang);
  window.dispatchEvent(new CustomEvent(LANG_CHANGE_EVENT, { detail: lang }));
}

